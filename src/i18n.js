/**
 * Get translation for key
 */
export const t = (path, lang = 'en') => {
  const keys = path.split('.');
  let value = TRANSLATIONS;
  
  for (const key of keys) {
    value = value?.[key];
  }
  
  if (typeof value === 'object' && value !== null) {
    return value[lang] || value.en || path;
  }
  
  return value || path;
};

/**
 * Get current language
 */
export const getCurrentLanguage = () => {
  const lang = localStorage.getItem('nexus_ui_language');
  return lang && SUPPORTED_LANGUAGES[lang] ? lang : 'en';
};

/**
 * Set language
 */
export const setLanguage = (lang) => {
  if (!SUPPORTED_LANGUAGES[lang]) {
    return { success: false, error: `Unsupported language: ${lang}` };
  }
  
  localStorage.setItem('nexus_ui_language', lang);
  
  // Update document direction for RTL languages
  document.documentElement.dir = SUPPORTED_LANGUAGES[lang].rtl ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  
  return { success: true, lang };
};

/**
 * Initialize language on app load
 */
export const initializeLanguage = () => {
  const lang = getCurrentLanguage();
  setLanguage(lang);
  return lang;
};

export default {
  SUPPORTED_LANGUAGES,
  TRANSLATIONS,
  t,
  getCurrentLanguage,
  setLanguage,
  initializeLanguage,
};
